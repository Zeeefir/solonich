begin;
create schema if not exists private;
create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 name text not null check(length(name) between 1 and 80),
 role text not null default 'customer' check(role in ('customer','admin'))
);
create table public.products (
 id bigint generated by default as identity primary key,
 content jsonb not null check(jsonb_typeof(content)='object')
);
create table private.visit_events (
 id uuid primary key,
 visitor_id uuid not null,
 session_id uuid not null,
 page_path text not null,
 occurred_at timestamptz not null default now()
);
create index on private.visit_events(visitor_id,occurred_at);
create index on private.visit_events(occurred_at);
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table private.visit_events enable row level security;
revoke all on public.profiles from anon,authenticated;
revoke all on public.products from anon,authenticated;
revoke all on private.visit_events from public,anon,authenticated;
grant select on public.profiles to authenticated;
grant select on public.products to anon,authenticated;
grant insert,update,delete on public.products to authenticated;
grant usage,select on sequence public.products_id_seq to authenticated;
grant usage on schema private to anon,authenticated;

create function private.is_admin() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;
revoke all on function private.is_admin() from public,anon,authenticated;
grant execute on function private.is_admin() to authenticated;
create policy own_profile on public.profiles for select to authenticated using(id=(select auth.uid()));
create policy public_catalog on public.products for select to anon,authenticated using(true);
create policy admin_insert on public.products for insert to authenticated with check((select private.is_admin()));
create policy admin_update on public.products for update to authenticated using((select private.is_admin())) with check((select private.is_admin()));
create policy admin_delete on public.products for delete to authenticated using((select private.is_admin()));

create function private.create_profile() returns trigger language plpgsql security definer set search_path='' as $$
begin
 insert into public.profiles(id,name,role) values(new.id,left(coalesce(nullif(trim(new.raw_user_meta_data->>'name'),''),'Покупатель'),80),'customer');
 return new;
end;
$$;
revoke all on function private.create_profile() from public,anon,authenticated;
create trigger on_signup after insert on auth.users for each row execute function private.create_profile();

create function private.record_visit(visitor_id uuid,session_id uuid,page_path text,event_id uuid) returns void language plpgsql security definer set search_path='' as $$
begin
 if visitor_id is null or session_id is null or event_id is null then return; end if;
 if page_path is null or (page_path<>'/' and page_path !~ '^/product/[0-9]{1,12}$') then return; end if;
 if exists(select 1 from public.profiles where id=auth.uid() and role='admin') then return; end if;
 if (select count(*) from private.visit_events e where e.visitor_id=record_visit.visitor_id and e.occurred_at>now()-interval '1 minute')>=30 then return; end if;
 insert into private.visit_events(id,visitor_id,session_id,page_path) values(event_id,visitor_id,session_id,page_path) on conflict(id) do nothing;
end;
$$;
revoke all on function private.record_visit(uuid,uuid,text,uuid) from public,anon,authenticated;
grant execute on function private.record_visit(uuid,uuid,text,uuid) to anon,authenticated;
create function public.record_visit(visitor_id uuid,session_id uuid,page_path text,event_id uuid) returns void language sql security invoker set search_path='' as $$
 select private.record_visit(visitor_id,session_id,page_path,event_id);
$$;
revoke all on function public.record_visit(uuid,uuid,text,uuid) from public,anon,authenticated;
grant execute on function public.record_visit(uuid,uuid,text,uuid) to anon,authenticated;

create function private.visitor_stats() returns jsonb language plpgsql security definer set search_path='' as $$
declare result jsonb;
begin
 if not private.is_admin() then raise exception 'Administrator access required' using errcode='42501'; end if;
 select jsonb_build_object(
  'visitorsTotal',count(distinct visitor_id),
  'visitsTotal',count(distinct session_id),
  'pageviewsTotal',count(*),
  'visitorsToday',count(distinct visitor_id) filter(where occurred_at>=(date_trunc('day',now() at time zone 'Asia/Qyzylorda') at time zone 'Asia/Qyzylorda'))
 ) into result from private.visit_events;
 return result;
end;
$$;
revoke all on function private.visitor_stats() from public,anon,authenticated;
grant execute on function private.visitor_stats() to authenticated;
create function public.visitor_stats() returns jsonb language sql security invoker set search_path='' as $$
 select private.visitor_stats();
$$;
revoke all on function public.visitor_stats() from public,anon,authenticated;
grant execute on function public.visitor_stats() to authenticated;

